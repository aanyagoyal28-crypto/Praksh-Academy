'''
operators - special type of symbols to do a spedific operation on the variables or values.
arithmetic operators - used to perform mathematical operations on numbers.
+ -> addition
- -> subtraction
* -> multiplication
/ -> division
// -> floor division
% -> modulus
** -> exponentiation(lhs will be having base and the rhs will be having index)
'''

num1 = input('Enter the first number = ')#25
num2 = input('Enter the second number = ')#60
print("Addition " , num1+num2)#85
print("Subtraction " , num1-num2)#-35
print("Multiplication " , num1*num2)#1500
print("Division " , num1/num2)#0.4166666666666667
print("Floor Division " , num1//num2)#0
print("Modulus " , num1%num2)#25
print("Exponentiation " , num1**num2)#25^60