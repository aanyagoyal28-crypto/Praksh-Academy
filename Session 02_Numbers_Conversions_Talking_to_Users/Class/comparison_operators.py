'''
= -> assignment operator(this operator assigns the value form the rhs to lhs)
comparison operators - used to compare two values.(= and ==)
== -> equal to
!= -> not equal to
< -> less than
> -> greater than
<= -> less than or equal to
>= -> greater than or equal to

all the outputs of the comparison operatos in in boolean format(True or False)
'''

num1 = 10
print(num1)

print(num1 == 10)#True
print(num1 != 10)#False
print(num1 < 10)#False(10<10)
print(num1 > 10)#False(10>10)
print(num1 <= 10)#True(10<=10)
print(num1 >= 10)#True(10>=10)

